/**
 * Write the site's PUBLIC build-time env (VITE_* only) into `.env.production.local`
 * so a LOCAL `npm run build` carries the same GA4 / Clarity / Pixel / Ads IDs that
 * Netlify injects in CI. Used before `safe-netlify-deploy.sh --prod --dir=build/client`
 * when `netlify deploy --build` cannot run on this machine.
 *
 *   node scripts/netlify-vite-env.mjs            # writes .env.production.local (gitignored via .env*)
 *   node scripts/netlify-vite-env.mjs --print    # lists KEY NAMES only, never values
 *
 * Only keys starting with VITE_ are written — server secrets (DEEPSEEK_API_KEY,
 * GM_CRM_BRIDGE_*) stay on Netlify where the functions read them at runtime.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const raw = execFileSync('netlify', ['env:list', '--json', '--context', 'production'], { cwd: ROOT, encoding: 'utf8', shell: true, stdio: ['ignore', 'pipe', 'ignore'] });
const all = JSON.parse(raw);
const entries = Object.entries(all).filter(([k]) => k.startsWith('VITE_'));
if (entries.length === 0) { console.error('no VITE_* keys returned — is the CLI linked to the right site?'); process.exit(1); }
if (process.argv.includes('--print')) { console.log(entries.map(([k]) => k).join('\n')); process.exit(0); }
const body = entries.map(([k, v]) => `${k}=${String(v).replace(/\r?\n/g, '')}`).join('\n') + '\n';
writeFileSync(join(ROOT, '.env.production.local'), `# generated by scripts/netlify-vite-env.mjs — public build-time IDs only, gitignored\n${body}`);
console.log(`wrote .env.production.local with ${entries.length} VITE_* key(s): ${entries.map(([k]) => k).join(', ')}`);
