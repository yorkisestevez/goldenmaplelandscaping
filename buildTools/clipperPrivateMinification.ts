/** The vendor module alone is transformed before bundling. Application
 * property names and the installed third-party source are never rewritten. */
export function clipperPrivateMinification():Plugin{return {name:'deckcraft-clipper-private-properties',apply:'build',enforce:'pre',async transform(code,id){
 if(!id.replaceAll('\\','/').endsWith('/node_modules/clipper-lib/clipper.js'))return null;
 const output=await minify(code,{compress:{passes:3},mangle:{properties:{regex:pattern}},format:{comments:'some'}});
 if(!output.code)throw Error('Clipper compilation produced no code.');return {code:output.code,map:null};
}};}
